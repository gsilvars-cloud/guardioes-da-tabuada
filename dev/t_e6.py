from gt import game, sheet
names = []; fails = []
def check(c, m):
    print(('  ok   ' if c else '  FALHA ') + m)
    if not c: fails.append(m)
with game(dsf=1) as pg:
    ev = pg.evaluate
    ev("() => { for (const f of __GT.FACTS.slice(0, 30)) __GT.recordAnswer(f.key, true, 1500, {}); __GT.save(); __GT.show('home'); }"); pg.wait_for_timeout(300)
    pg.screenshot(path='tmp/f0.png'); names.append('tmp/f0.png')
    c0 = ev("() => __GT.S.coins")
    pg.click('#afiarBtn'); pg.wait_for_timeout(300)
    check(ev("() => !!__GT.AF"), 'Afiar runas abre')
    for i in range(5):
        a = str(ev("() => __GT.AF.q.ans"))
        for ch in a: pg.keyboard.press(ch)
        pg.wait_for_timeout(220)
    pg.screenshot(path='tmp/f1.png'); names.append('tmp/f1.png')
    a = ev("() => __GT.AF.q.ans"); wrong = str(a + 1 if a < 99 else 10).zfill(len(str(a)))
    for ch in wrong[:len(str(a))]: pg.keyboard.press(ch)
    pg.wait_for_timeout(200); pg.screenshot(path='tmp/f2.png'); names.append('tmp/f2.png'); pg.wait_for_timeout(1100)
    r = ev("() => ({n:__GT.AF.n, miss:__GT.AF.miss.length})")
    check(r['n'] == 5 and r['miss'] == 1, f'5 certas e 1 errada {r}')
    ev("() => { __GT.S.sombra = {n:3, day:0, beaten:false}; __GT.AF.endAt = 0; }"); pg.wait_for_timeout(400)
    pg.screenshot(path='tmp/f3.png'); names.append('tmp/f3.png')
    r = ev("() => ({af:__GT.S.afiar, coins:__GT.S.coins, sb:__GT.S.sombra, open:!!__GT.AF})")
    check(r['af']['best'] == 5 and r['coins'] == c0 + 10 + 40 and r['sb']['beaten'] and not r['open'], f'recorde, moedas e sombra batida {r}')
    pg.click('#afClose'); pg.wait_for_timeout(200)
    check('missão feita' in ev("() => document.getElementById('afiarBtn').textContent"), 'botão mostra missão feita')
    ev("() => { __GT.show('settings'); __GT.paiReport(); }"); pg.wait_for_timeout(200)
    ev("() => document.querySelector('#modal .sheet').scrollTo(0, 9999)"); pg.wait_for_timeout(150); pg.screenshot(path='tmp/f4.png'); names.append('tmp/f4.png')
    pg.click('#paiSombra'); pg.wait_for_timeout(250)
    check(ev("() => __GT.AF && __GT.AF.dad && __GT.AF.pool.every(f => f.a >= 3 && f.b >= 6)"), 'sombra do papai usa só contas difíceis')
    n0 = ev("() => __GT.S.stats.answered")
    for i in range(3):
        a = str(ev("() => __GT.AF.q.ans"))
        for ch in a: pg.keyboard.press(ch)
        pg.wait_for_timeout(220)
    pg.screenshot(path='tmp/f5.png'); names.append('tmp/f5.png')
    ev("() => { __GT.AF.endAt = 0; }"); pg.wait_for_timeout(400)
    r = ev("() => ({sb:__GT.S.sombra, ans:__GT.S.stats.answered})")
    check(r['sb']['n'] == 3 and not r['sb']['beaten'] and r['ans'] == n0, f'sombra gravada sem mexer no aprendizado dela {r}')
    pg.click('#afClose'); pg.wait_for_timeout(150)
    check(not pg.errs, f'sem erros {pg.errs[:2]}')
sheet(names, 'tmp/e6.jpg', 2)
print('FALHAS:', fails or 'nenhuma')
